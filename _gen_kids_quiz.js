// Deduplicate cards_kids_quiz.js and fill to 150 per level
const fs = require('fs');
const path = require('path');

const file = path.join(__dirname, 'cards/cards_kids_quiz.js');
let content = fs.readFileSync(file, 'utf8');

// Parse existing cards with regex
const cardRegex = /\{level:(\d), q:'([^']*)', a:\[([^\]]*)\]\}/g;
let match;
const levels = {1:[], 2:[], 3:[], 4:[]};

while((match = cardRegex.exec(content)) !== null){
  const level = parseInt(match[1]);
  const q = match[2];
  const answers = match[3];
  levels[level].push({q, answers, raw: match[0]});
}

console.log('Before dedup:');
for(let i=1; i<=4; i++){
  console.log(`  Level ${i}: ${levels[i].length} cards`);
}

// Deduplicate: keep first occurrence of each question text
for(let i=1; i<=4; i++){
  const seen = new Set();
  const deduped = [];
  for(const card of levels[i]){
    if(!seen.has(card.q)){
      seen.add(card.q);
      deduped.push(card);
    }
  }
  levels[i] = deduped;
}

console.log('After dedup:');
for(let i=1; i<=4; i++){
  console.log(`  Level ${i}: ${levels[i].length} unique cards (need ${150 - levels[i].length} more)`);
}

