// Helper to format a card
function cardStr(level, q, correct, distractors){
  const opts = [correct, ...distractors];
  return `  {level:${level}, q:'${q}', a:[${opts.map(o=>"'" + o + "'").join(', ')}]}`;
}

// Function to get unique questions for a level
function getUniqueCards(levelArr){
  const seen = new Set();
  return levelArr.filter(card => {
    if(seen.has(card.q)){
      return false;
    }
    seen.add(card.q);
    return true;
  });
}

