// 1–8, затем 25–31. Перенумеровывать их нельзя: от id зависят сохранённые
// карты (state.knowMoreLog / knowMoreHistory), и смена номера переписала бы
// прошлые партии. На игру порядок строк не влияет — очередь строится по полю
// level. Раньше файл был разбит на шесть секций («уровень 1–3», потом ещё
// «уровень 1–3»), и зоны одного уровня приходилось искать в двух местах.

// Тексты написаны нейтрально и уважительно: игра про внимание к другому
// человеку, а не про давление. Зона, которая не понравилась, честно
