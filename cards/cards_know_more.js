// KNOW_MORE_ZONES — зоны тела, которые партнёры исследуют по очереди.
// У каждой зоны:
//   id    — уникальный номер (ключ в сохранённой карте);
//   icon  — иконка зоны. С 2026-09-29 по решению владельца НЕ рисуется:
//     ни на карточке задания, ни в списке «Исследованные» (там иконки
//     повторялись названию и только отвлекали). Поле оставлено в данных,
//     чтобы вернуть иконки было одной правкой в games/know-more.js, а не
//     вбиванием 48 эмодзи заново; использует его только значок зоны;
//   name  — название зоны (её видят оба);
//   part  — часть тела (мелкой подписью под названием);
//   body  — 'he' или 'she', если зона есть только у одного из партнёров
//     (например, зоны интимной группы). Поле необязательное: у зон,
//     общих для обоих, его нет. Карточка показывает по нему «Его тело» или
//     «Её тело», а список «Исследованные» и итоги — «… (Он)» / «… (Она)».
//     Без этого «Мошонка» или «Клитор» висели бы в воздухе: непонятно,
//     чьё тело сейчас исследуют.
//   how   — подсказка ИССЛЕДОВАТЕЛЮ: что и как делать руками;
//   howByTool — те же подсказки для остальных способов из настройки
//     «Чем исследуют»: 1 — губы и язык, 2 — перо или ткань, 3 — вибрация.
//     Ключ 0 (руки) не пишется: для него и есть поле how. На карточке
//     показывается подсказка выбранного способа, а если варианта для него
//     нет — обычная, ручная. Вариант пишется для ВСЕХ 48 зон и всех трёх
//     способов: запретов тут нет. Решение о том, приятна ли вибрация в зоне,
//     принимает игрок, а не текст, — даже там, где прибор физически не
//     проходит внутрь (простата, точка G), вибрация снаружи работает и вполне
//     может быть приятной, поэтому такие зоны описаны через внешний доступ.
//     Где нужна осторожность (мелкие и хрупкие зоны вроде пальцев ног), она
//     описана техникой: слабая мощность, не прижимать, следить за реакцией.
//   level — 1 (нежно) / 2 (средне) / 3 (смелее). Это порядок партии: очередь
//     строится от нежных зон к более чувствительным, внутри уровня — случайно,
//     так что партия всегда мягко начинается и плавно идёт дальше.
//
// ПОРЯДОК В ФАЙЛЕ. Зоны сгруппированы по уровню, ровно тремя секциями, внутри
// секции — по возрастанию id. Собранные на два захода (сначала 1–24, потом
