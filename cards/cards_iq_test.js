//
// ПОЧЕМУ НЕТ ЧИСЛА IQ — ВАЖНО, И ЭТО СКАЗАНО ИГРОКУ
// Настоящий тест интеллекта (WAIS, Stanford-Binet и их аналоги) — это
// стандартизированная методика с референсной группой, нормами и поправками на
// возраст. Здесь ничего этого нет: вопросы написаны для приложения, выборка
// пользователей не измерялась, психометрической проверки не проходилось.
// Поэтому игра НЕ называет результат «IQ» и не притворяется, что измеряет
// интеллект в смысле, из которого его выводят специалисты. То же касается
// «эффекта Флинга», IQ не наследуется и врождённого интеллекта — игра не
// говорит ничего из этого. Заявление об IQ по результату такой игры было бы
// просто неверным, поэтому вместо него — профиль по направлениям и разбор.
//
// ПРО АВТОРСКИЕ ПРАВА
// Все 30 вопросов и вариантов ответа написаны для этого приложения. Формат
// вопросов (числовой ряд, аналогия, дедукция, «на что похоже», работа с
// текстом) — общий тип заданий, он встречается в любом учебнике логики, но
// конкретные задания здесь новые: ничего не переведено и не скопировано из
// тестов Равена, Амтхауэра, Уискенда, Гулфорда, а также из сборников
// «тестов IQ», которые защищены авторским правом.
//
